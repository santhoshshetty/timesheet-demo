import type { ReactNode, Ref } from 'react';
import Box from '@mui/material/Box';
import Button from '@mui/material/Button';
import FormControl from '@mui/material/FormControl';
import FormControlLabel from '@mui/material/FormControlLabel';
import FormHelperText from '@mui/material/FormHelperText';
import FormLabel from '@mui/material/FormLabel';
import Paper from '@mui/material/Paper';
import Radio from '@mui/material/Radio';
import RadioGroup from '@mui/material/RadioGroup';
import Stack from '@mui/material/Stack';
import TextField from '@mui/material/TextField';
import Typography from '@mui/material/Typography';
import { ErrorSummary } from '../../shared/ErrorSummary';
import { ChargeCodeText } from './ChargeCodeText';
import { BILLING_TYPE_LABELS, PROJECT_TYPE_LABELS } from './labels';
import {
  PROJECT_FIELDS,
  fieldId,
  type FieldErrors,
  type ProjectField,
  type ProjectFormValues,
} from './validation';

type TextKey = Exclude<keyof ProjectFormValues, 'projectType' | 'billingType'>;

interface ProjectFormProps {
  values: ProjectFormValues;
  errors: FieldErrors;
  showErrorSummary: boolean;
  errorSummaryRef?: Ref<HTMLDivElement>;
  startDateHint?: string;
  chargeCode?: string;
  submitting: boolean;
  submitLabel: string;
  onChange: (values: ProjectFormValues) => void;
  onSubmit: () => void;
  onCancel?: () => void;
}

function Section({ title, children }: { title: string; children: ReactNode }) {
  const headingId = `section-${title.toLowerCase().replace(/\s+/g, '-')}`;
  return (
    <Paper component="section" sx={{ p: 3 }} aria-labelledby={headingId}>
      <Typography variant="h2" component="h2" id={headingId} sx={{ mb: 2 }}>
        {title}
      </Typography>
      <Stack spacing={2.5}>{children}</Stack>
    </Paper>
  );
}

interface ChoiceFieldProps<T extends string> {
  field: ProjectField;
  label: string;
  value: T | '';
  options: Record<T, string>;
  error?: string;
  onChange: (value: T) => void;
}

function ChoiceField<T extends string>({
  field,
  label,
  value,
  options,
  error,
  onChange,
}: ChoiceFieldProps<T>) {
  const id = fieldId(field);
  const helperId = `${id}-helper-text`;
  return (
    <FormControl component="fieldset" required error={Boolean(error)}>
      <FormLabel component="legend">{label}</FormLabel>
      <RadioGroup
        row
        name={id}
        value={value}
        onChange={(event) => onChange(event.target.value as T)}
        aria-describedby={error ? helperId : undefined}
      >
        {(Object.entries(options) as Array<[T, string]>).map(([option, optionLabel], index) => (
          <FormControlLabel
            key={option}
            value={option}
            label={optionLabel}
            control={<Radio id={index === 0 ? id : undefined} />}
          />
        ))}
      </RadioGroup>
      {error && <FormHelperText id={helperId}>{error}</FormHelperText>}
    </FormControl>
  );
}

export function ProjectForm({
  values,
  errors,
  showErrorSummary,
  errorSummaryRef,
  startDateHint,
  chargeCode,
  submitting,
  submitLabel,
  onChange,
  onSubmit,
  onCancel,
}: ProjectFormProps) {
  const set = <K extends keyof ProjectFormValues>(key: K, value: ProjectFormValues[K]) =>
    onChange({ ...values, [key]: value });

  const summaryItems = PROJECT_FIELDS.filter((field) => errors[field]).map((field) => ({
    fieldId: fieldId(field),
    message: errors[field] ?? '',
  }));

  const text = (field: ProjectField, label: string, key: TextKey, type = 'text') => (
    <TextField
      id={fieldId(field)}
      label={label}
      type={type}
      required
      fullWidth
      value={values[key]}
      onChange={(event) => onChange({ ...values, [key]: event.target.value })}
      error={Boolean(errors[field])}
      helperText={errors[field] ?? (field === 'startDate' ? startDateHint : undefined)}
      slotProps={type === 'date' ? { inputLabel: { shrink: true } } : undefined}
    />
  );

  return (
    <Box
      component="form"
      noValidate
      onSubmit={(event) => {
        event.preventDefault();
        onSubmit();
      }}
    >
      {showErrorSummary && summaryItems.length > 0 && (
        <ErrorSummary ref={errorSummaryRef} items={summaryItems} />
      )}
      <Typography variant="body2" color="text.secondary" sx={{ mb: 2 }}>
        Fields marked with * are required.
      </Typography>
      <Stack spacing={3}>
        <Section title="General">
          {chargeCode && (
            <Box>
              <Typography variant="body2" color="text.secondary">
                Charge code (generated by the system, cannot be changed)
              </Typography>
              <ChargeCodeText code={chargeCode} />
            </Box>
          )}
          {text('name', 'Project name', 'name')}
          <ChoiceField
            field="projectType"
            label="Project type"
            value={values.projectType}
            options={PROJECT_TYPE_LABELS}
            error={errors.projectType}
            onChange={(value) => set('projectType', value)}
          />
          {values.projectType === 'CLIENT' && text('clientName', 'Client name', 'clientName')}
        </Section>

        <Section title="Project manager">
          {text('projectManager.name', 'Project manager name', 'projectManagerName')}
          {text('projectManager.email', 'Project manager email', 'projectManagerEmail', 'email')}
        </Section>

        <Section title="Schedule">
          {text('startDate', 'Start date', 'startDate', 'date')}
          {text('endDate', 'End date', 'endDate', 'date')}
        </Section>

        <Section title="Billing">
          <ChoiceField
            field="billingType"
            label="Billing type"
            value={values.billingType}
            options={BILLING_TYPE_LABELS}
            error={errors.billingType}
            onChange={(value) => set('billingType', value)}
          />
        </Section>

        <Stack direction="row" spacing={2}>
          <Button type="submit" variant="contained" disabled={submitting}>
            {submitting ? 'Saving…' : submitLabel}
          </Button>
          {onCancel && (
            <Button variant="outlined" onClick={onCancel} disabled={submitting}>
              Cancel
            </Button>
          )}
        </Stack>
      </Stack>
    </Box>
  );
}
