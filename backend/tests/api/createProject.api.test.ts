import { randomUUID } from 'node:crypto';
import request from 'supertest';
import { EmailAddress } from '../../src/domain/project/EmailAddress';
import { ACCEPTED_EMAILS, REJECTED_EMAILS } from '../support/emailCases';
import { SequenceChargeCodeGenerator, TODAY } from '../support/fakes';
import { getPool, stop, truncateProjects } from '../support/postgres';
import { buildTestApp } from '../support/testApp';

const validBody = {
  name: 'Apollo Migration',
  projectManager: { name: 'Priya Shah', email: 'priya.shah@example.com' },
  startDate: TODAY,
  endDate: '2026-12-31',
  projectType: 'CLIENT',
  clientName: 'Contoso',
  billingType: 'BILLABLE',
};

function post(app: ReturnType<typeof buildTestApp>, body: object, key: string = randomUUID()) {
  return request(app).post('/api/v1/projects').set('Idempotency-Key', key).send(body);
}

function expectProblem(res: request.Response, status: number, code: string) {
  expect(res.status).toBe(status);
  expect(res.headers['content-type']).toMatch(/application\/problem\+json/);
  expect(res.body).toMatchObject({ status, code });
  expect(typeof res.body.requestId).toBe('string');
  expect(JSON.stringify(res.body)).not.toMatch(/stack|at .*\.ts:\d+|SELECT|INSERT/);
}

function fieldCodes(res: request.Response): Array<[string, string]> {
  return (res.body.errors as Array<{ field: string; code: string }>).map((e) => [e.field, e.code]);
}

describe('POST /api/v1/projects', () => {
  const app = buildTestApp();

  beforeEach(async () => {
    await truncateProjects();
  });

  afterAll(async () => {
    await stop();
  });

  it('creates a project with a generated 8-digit charge code', async () => {
    const res = await post(app, validBody).expect(201);
    expect(res.headers.location).toBe(`/api/v1/projects/${res.body.id}`);
    expect(res.headers.etag).toBe('"1"');
    expect(res.body.chargeCode).toMatch(/^[0-9]{8}$/);
    expect(res.body).toMatchObject({
      name: 'Apollo Migration',
      projectManager: { name: 'Priya Shah', email: 'priya.shah@example.com' },
      startDate: TODAY,
      clientName: 'Contoso',
      version: 1,
    });
  });

  it('returns the same project with 200 when the same Idempotency-Key is repeated', async () => {
    const key = randomUUID();
    const first = await post(app, validBody, key).expect(201);
    const second = await post(app, validBody, key).expect(200);
    expect(second.body.id).toBe(first.body.id);
    expect(second.body.chargeCode).toBe(first.body.chargeCode);
    const { rows } = await getPool().query('SELECT count(*)::int AS n FROM project');
    expect(rows[0].n).toBe(1);
  });

  it('requires the Idempotency-Key header', async () => {
    const res = await request(app).post('/api/v1/projects').send(validBody);
    expectProblem(res, 400, 'VALIDATION_FAILED');
    expect(fieldCodes(res)).toContainEqual(['Idempotency-Key', 'REQUIRED']);
  });

  it('reports every missing required field', async () => {
    const res = await post(app, {});
    expectProblem(res, 400, 'VALIDATION_FAILED');
    expect(fieldCodes(res)).toEqual(
      expect.arrayContaining([
        ['name', 'REQUIRED'],
        ['projectManager', 'REQUIRED'],
        ['startDate', 'REQUIRED'],
        ['endDate', 'REQUIRED'],
        ['projectType', 'REQUIRED'],
        ['billingType', 'REQUIRED'],
      ]),
    );
  });

  it('rejects an empty name with REQUIRED (schema minLength)', async () => {
    const res = await post(app, { ...validBody, name: '' });
    expectProblem(res, 400, 'VALIDATION_FAILED');
    expect(fieldCodes(res)).toContainEqual(['name', 'REQUIRED']);
  });

  it('rejects a supplied charge code', async () => {
    const res = await post(app, { ...validBody, chargeCode: '12345678' });
    expectProblem(res, 400, 'VALIDATION_FAILED');
    expect(res.body.errors).toContainEqual({
      field: 'chargeCode',
      code: 'UNKNOWN_FIELD',
      message: 'Charge code is generated by the system and cannot be supplied.',
    });
  });

  it('rejects an unknown project type', async () => {
    const res = await post(app, { ...validBody, projectType: 'OTHER' });
    expectProblem(res, 400, 'VALIDATION_FAILED');
    expect(fieldCodes(res)).toContainEqual(['projectType', 'INVALID_VALUE']);
  });

  it.each([
    ['a start date in the past', { startDate: '2026-10-05' }, ['startDate', 'START_DATE_IN_PAST']],
    [
      'an end date before the start date',
      { endDate: '2026-10-05' },
      ['endDate', 'END_BEFORE_START'],
    ],
    [
      'a client project without client name',
      { clientName: null },
      ['clientName', 'CLIENT_NAME_REQUIRED'],
    ],
    ['a name of spaces only', { name: '   ' }, ['name', 'REQUIRED']],
  ])('rejects %s with 422', async (_label, change, expected) => {
    const res = await post(app, { ...validBody, ...change });
    expectProblem(res, 422, 'BUSINESS_RULE_VIOLATION');
    expect(fieldCodes(res)).toContainEqual(expected);
  });

  it('rejects a duplicate name ignoring case with 409', async () => {
    await post(app, validBody).expect(201);
    const res = await post(app, { ...validBody, name: 'apollo migration' });
    expectProblem(res, 409, 'PROJECT_NAME_TAKEN');
    expect(fieldCodes(res)).toEqual([['name', 'INVALID_VALUE']]);
  });

  it('returns 503 and stores nothing when no unique charge code can be generated', async () => {
    const colliding = buildTestApp({ chargeCodes: new SequenceChargeCodeGenerator(['00000001']) });
    await post(colliding, validBody).expect(201);
    const res = await post(colliding, { ...validBody, name: 'Second' });
    expectProblem(res, 503, 'CHARGE_CODE_UNAVAILABLE');
    const { rows } = await getPool().query('SELECT count(*)::int AS n FROM project');
    expect(rows[0].n).toBe(1);
  });

  it('gives 20 parallel creates 20 distinct charge codes', async () => {
    const responses = await Promise.all(
      Array.from({ length: 20 }, (_, i) => post(app, { ...validBody, name: `Parallel ${i}` })),
    );
    expect(responses.every((r) => r.status === 201)).toBe(true);
    const codes = new Set(responses.map((r) => r.body.chargeCode as string));
    expect(codes.size).toBe(20);
  });

  it('accepts and rejects the same emails as the domain', async () => {
    for (const [index, email] of [...ACCEPTED_EMAILS, ...REJECTED_EMAILS].entries()) {
      const res = await post(app, {
        ...validBody,
        name: `Email ${index}`,
        projectManager: { name: 'Priya', email },
      });
      const domainAccepts = EmailAddress.parse(email).ok;
      expect([email, res.status === 201]).toEqual([email, domainAccepts]);
      if (!domainAccepts) {
        expect(res.status).toBe(400);
      }
    }
  });
});
